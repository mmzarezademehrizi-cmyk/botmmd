# -*- coding: utf-8 -*-
"""
تنظیمات ثابت ربات.

نکته‌ی مهم درباره‌ی ورود مالک (/ownerlogin):
یوزرنیم/پسورد مالک دیگه اینجا (توی این فایل) تعریف نمی‌شه. از این به بعد
یک منبع واحده: همون یوزرنیم/پسوردی که بار اولی که سایت رو بالا میاری
می‌سازی (یا بعداً از تب «حساب مالک» توی پنل عوضش می‌کنی). هر کسی که توی
پیوی ربات دستور /ownerlogin رو بزنه و دقیقاً همین یوزرنیم/پسورد (همون‌ سایتی)
رو وارد کنه، همون لحظه چت‌آیدی‌اش به‌عنوان «مالک ربات» ثبت می‌شه.

یعنی اگه می‌خوای یوزرنیم/پسورد ورود مالک (چه توی سایت، چه توی ربات) رو
عوض کنی، فقط از پنل سایت (تب حساب مالک) عوضش کن - همون‌جا برای هر دو
جواب می‌ده. اگه هنوز اصلاً سایت رو بار اول بالا نیاوردی، /ownerlogin توی
ربات هم جواب نمی‌ده (باید اول یک بار سایت رو باز کنی و یوزرنیم/پسورد
اولیه رو اونجا بسازی).
"""

from base.paths import ROOT
import os
import sys

BASE_DIR = ROOT

# اگه نه متغیرِ محیطی نه فایل پیدا نشد، به‌جایِ کرش‌کردنِ فوریِ import
# (که تست‌ها و اسکریپت‌هایی که فقط می‌خوان config/core رو ایمپورت کنن و
# بعداً خودشون BOT_TOKEN رو ست‌کنن رو خراب می‌کنه)، یه مقدارِ ساختگیِ
# قابل‌تشخیص برمی‌گردونیم. خودِ main.py (نقطه‌یِ واقعیِ اجرایِ بات) قبل از
# اتصال به تلگرام صریحاً چک می‌کنه که این مقدار عوض شده باشه.
_PLACEHOLDER_TOKEN = "0:MISSING_BOT_TOKEN_SET_ENV_VAR_OR_DOT_BOT_TOKEN_FILE"


def _load_bot_token() -> str:
    """
    امنیتی: قبلاً توکنِ واقعیِ بات همین‌جا، توی خودِ کد، به‌صورت متنِ ساده
    نوشته شده بود - یعنی هرجا این پروژه (زیپ/گیت/بکاپ) دست‌به‌دست بشه،
    توکن هم باهاش می‌ره. توکنِ بات دقیقاً معادلِ رمزِ کاملِ باته: هرکی
    داشته باشدش می‌تونه کاملاً جایِ بات بشینه (پیام بفرسته، فایل بخونه،
    حتی وبهوکش رو عوض کنه). از این به بعد توکن یا از متغیرِ محیطیِ
    BOT_TOKEN خونده می‌شه، یا (برایِ راحتیِ اجرایِ محلی، دقیقاً شبیهِ
    الگویِ WEB_SECRET_KEY توی web_app.py) از یه فایلِ کنارِ همین پروژه که
    توی گیت کامیت نمی‌شه (.bot_token).

    ⚠️ توکنی که قبلاً همین‌جا هاردکد بود (که با ...IqjKs88Y تموم می‌شد)
    از این به بعد باید «سوخته‌شده» در نظر گرفته بشه - چون همین پروژه
    (با همون توکن توش) چندبار به‌صورتِ فایل جابه‌جا شده. حتماً از
    @BotFather با دستورِ /revoke یا /token یه توکنِ کاملاً جدید بگیر و
    همون جدید رو (نه قدیمی رو) ست کن.
    """
    env_token = os.environ.get("BOT_TOKEN")
    if env_token:
        return env_token
    token_path = os.path.join(BASE_DIR, ".bot_token")
    if os.path.isfile(token_path):
        with open(token_path, "r", encoding="utf-8") as f:
            t = f.read().strip()
        if t:
            return t
    print(
        "⚠️  BOT_TOKEN تنظیم نشده (نه متغیرِ محیطیِ BOT_TOKEN، نه فایلِ .bot_token). "
        "تا وقتی درستش نکنی، بات نمی‌تونه واقعاً به تلگرام وصل بشه.",
        file=sys.stderr,
    )
    return _PLACEHOLDER_TOKEN


BOT_TOKEN = _load_bot_token()
